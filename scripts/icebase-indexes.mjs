// Writes backend/src/icebase/indexes.ts: the composite indexes of backend/firestore.indexes.json
// plus every index IceBase reported missing while the tests ran in learning mode
// (ICEBASE_LEARN=<file>). Existing entries are kept.
//   node scripts/icebase-indexes.mjs [learned.jsonl ...]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const out = 'backend/src/icebase/indexes.ts';
const schemaSrc = readFileSync('backend/src/icebase/schema.ts', 'utf8');
const templates = [...schemaSrc.matchAll(/^\s+'?([A-Za-z_{}/]+)'?: (?:'[A-Za-z]+'|null),$/gm)].map((m) => m[1]);
const idOf = (t) => t.slice(t.lastIndexOf('/') + 1);

/** firestore.indexes.json keys composites by collection id; these do not apply to every collection with that id. */
const EXCLUDE = { 'boards/{boardId}/webhooks/{webhookId}/deliveries': ["index('uid', desc('createdAt'))"] };

/** template → Set of index(…) code */
const indexes = new Map();
const add = (t, code) => {
  if (EXCLUDE[t]?.includes(code)) return;
  if (!indexes.has(t)) indexes.set(t, new Set());
  indexes.get(t).add(code);
};
// keep what is there
if (existsSync(out)) {
  for (const m of readFileSync(out, 'utf8').matchAll(/^ {2}'([^']+)': \[\n((?: {4}.+\n)*?) {2}\],$/gm)) for (const l of m[2].trim().split('\n')) add(m[1], l.trim().replace(/,$/, ''));
}
const key = (p) => {
  const segs = p.split('.');
  return segs.length === 1 ? `'${segs[0]}'` : `[${segs.map((s) => `'${s}'`).join(', ')}]`;
};
const fx = JSON.parse(readFileSync('backend/firestore.indexes.json', 'utf8'));
for (const ix of fx.indexes) {
  const parts = ix.fields.filter((f) => f.fieldPath !== '__name__').map((f) => (f.arrayConfig ? `contains(${key(f.fieldPath)})` : f.order === 'DESCENDING' ? `desc(${key(f.fieldPath)})` : key(f.fieldPath)));
  const code = `index(${parts.join(', ')})`;
  for (const t of templates.filter((t) => idOf(t) === ix.collectionGroup)) add(t, code);
}
for (const file of process.argv.slice(2)) {
  for (const line of readFileSync(file, 'utf8').split('\n').filter(Boolean)) {
    const i = JSON.parse(line);
    if (i.kind !== 'index' || !i.suggestion) continue;
    // "index('a'), index('b')" → each one
    // A key that is data (an agent id in a record) is any key: '*'.
    for (const one of i.suggestion.match(/index\((?:[^()]|\([^()]*\))*\)/g) ?? []) add(i.collection, one.replace(/'ag_[A-Za-z0-9]+'/g, "'*'"));
  }
}
const body = [...indexes].sort(([a], [b]) => (a < b ? -1 : 1)).map(([t, set]) => `  '${t}': [\n${[...set].sort().map((c) => `    ${c},`).join('\n')}\n  ],`);
writeFileSync(
  out,
  `/**
 * Every index TaskManager's queries use, per collection path template — single-field ones too
 * (IceBase refuses a query whose index is not declared). Generated by scripts/icebase-indexes.mjs
 * from backend/firestore.indexes.json plus the queries the test suites run; edit freely.
 */
import { contains, desc, index, type IndexSpec } from '@panth977/icebase/schema';

export const INDEXES: Record<string, IndexSpec<string>[]> = {
${body.join('\n')}
};
`,
);
console.log(`${out}: ${[...indexes.values()].reduce((n, s) => n + s.size, 0)} indexes on ${indexes.size} collections`);
